                pages: 20 // number of pages
            }),
        columns: [
            { data: 'DT_RowIndex', name: 'id' },
            { data: 'city', name: 'city' },
            { data: 'address2', name: 'address2' },
            { data: 'zip5', name: 'zip5' },
            { data: 'state', name: 'state' ,orderable:false},
            {data: 'action', name: 'action', orderable: false, searchable: false}
        ]
    });
});
